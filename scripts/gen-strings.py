#!/usr/bin/env python3
"""Compile Packaging/Localizable.xcstrings into <lang>.lproj/Localizable.strings files.

SwiftPM's `swift build` copies .xcstrings verbatim instead of compiling them, and
NSBundle then rescans the bundle on every lookup. The .lproj output is what the runtime
actually wants. Run after editing the catalog; the output is committed.
"""
import json, pathlib, sys

root = pathlib.Path(__file__).resolve().parent.parent
catalog = json.loads((root / "Packaging/Localizable.xcstrings").read_text())
out = root / "Sources/DollarAppleUI/Resources"
langs = sorted({lang for entry in catalog["strings"].values() for lang in entry.get("localizations", {})})

def esc(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")

for lang in langs:
    lines = ["/* Generated by scripts/gen-strings.py from Packaging/Localizable.xcstrings. Do not edit. */", ""]
    for key in sorted(catalog["strings"]):
        loc = catalog["strings"][key].get("localizations", {}).get(lang)
        if not loc:
            continue
        lines.append(f'"{esc(key)}" = "{esc(loc["stringUnit"]["value"])}";')
    target = out / f"{lang}.lproj"
    target.mkdir(parents=True, exist_ok=True)
    (target / "Localizable.strings").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{lang}: {len(lines) - 2} strings")
